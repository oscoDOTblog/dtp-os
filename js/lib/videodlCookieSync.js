import {
  ALARM_NAME,
  COOKIES_PERMISSION,
  getVideodlCookieSettings,
  saveVideodlCookieSyncState,
} from "./videodlCookieSettings.js";

const ALLOWED_DOMAIN_SUFFIXES = [
  "youtube.com",
  "youtu.be",
  "youtube-nocookie.com",
  "google.com",
  "googleapis.com",
  "gstatic.com",
  "ggpht.com",
  "googlevideo.com",
  "googleusercontent.com",
];

const LOGIN_COOKIE_NAMES = new Set([
  "SID",
  "__Secure-1PSID",
  "__Secure-3PSID",
  "LOGIN_INFO",
  "SAPISID",
  "__Secure-1PAPISID",
  "__Secure-3PAPISID",
]);

function isSafeCookieToken(value) {
  return typeof value === "string" && value.length > 0 && !/[\t\r\n]/.test(value);
}

export function isAllowedCookieDomain(domain) {
  const host = String(domain || "")
    .replace(/^\./, "")
    .toLowerCase();
  if (!host) {
    return false;
  }
  return ALLOWED_DOMAIN_SUFFIXES.some(
    (suffix) => host === suffix || host.endsWith(`.${suffix}`)
  );
}

export function hasYoutubeLoginCookies(cookies) {
  return (cookies || []).some((cookie) => LOGIN_COOKIE_NAMES.has(cookie.name));
}

export function assertLoopbackApiUrl(url) {
  let parsed;
  try {
    parsed = new URL(String(url || "").trim());
  } catch {
    throw new Error("VideoDL API URL is invalid.");
  }
  if (parsed.protocol !== "http:") {
    throw new Error("VideoDL API URL must use http:// on loopback.");
  }
  if (parsed.hostname !== "127.0.0.1" && parsed.hostname !== "localhost") {
    throw new Error("VideoDL API URL must be 127.0.0.1 or localhost.");
  }
  if (parsed.username || parsed.password) {
    throw new Error("VideoDL API URL must not include credentials.");
  }
  return parsed.origin;
}

export function cookieToNetscapeLine(cookie) {
  if (!cookie || !isSafeCookieToken(cookie.name) || typeof cookie.value !== "string") {
    return null;
  }
  if (/[\t\r\n]/.test(cookie.value)) {
    return null;
  }

  const httpOnlyPrefix = cookie.httpOnly ? "#HttpOnly_" : "";
  let domain = String(cookie.domain || "");
  if (!domain) {
    return null;
  }
  const includeSubdomains = cookie.hostOnly ? "FALSE" : "TRUE";
  if (!cookie.hostOnly && !domain.startsWith(".")) {
    domain = `.${domain}`;
  }
  const path = cookie.path || "/";
  if (/[\t\r\n]/.test(path)) {
    return null;
  }
  const secure = cookie.secure ? "TRUE" : "FALSE";
  const expiry =
    cookie.session || typeof cookie.expirationDate !== "number"
      ? 0
      : Math.floor(cookie.expirationDate);

  return `${httpOnlyPrefix}${domain}\t${includeSubdomains}\t${path}\t${secure}\t${expiry}\t${cookie.name}\t${cookie.value}`;
}

export function cookiesToNetscape(cookies) {
  const lines = (cookies || [])
    .map((cookie) => cookieToNetscapeLine(cookie))
    .filter(Boolean);
  return ["# Netscape HTTP Cookie File", "# Generated by dtp-os for local VideoDL.", "", ...lines].join(
    "\n"
  );
}

export async function hasCookiesPermission() {
  return chrome.permissions.contains({ permissions: [COOKIES_PERMISSION] });
}

export async function requestCookiesPermission() {
  const already = await hasCookiesPermission();
  if (already) {
    return true;
  }
  return chrome.permissions.request({ permissions: [COOKIES_PERMISSION] });
}

function cookieIdentity(cookie) {
  return `${cookie.domain}\0${cookie.path}\0${cookie.name}`;
}

async function collectAllowedCookies() {
  const unpartitioned = await Promise.all(
    ALLOWED_DOMAIN_SUFFIXES.map((domain) => chrome.cookies.getAll({ domain }))
  );
  let partitioned = [];
  try {
    partitioned = await Promise.all(
      ALLOWED_DOMAIN_SUFFIXES.map((domain) =>
        chrome.cookies.getAll({
          domain,
          partitionKey: { topLevelSite: "https://www.youtube.com" },
        })
      )
    );
  } catch {
    // partitionKey is unavailable on older Chromium.
  }

  const seen = new Set();
  const allowed = [];
  for (const cookie of [...unpartitioned.flat(), ...partitioned.flat()]) {
    if (!isAllowedCookieDomain(cookie.domain)) {
      continue;
    }
    const key = cookieIdentity(cookie);
    if (seen.has(key)) {
      continue;
    }
    seen.add(key);
    allowed.push(cookie);
  }
  return allowed;
}

function mapFetchError(error, origin) {
  const message = error?.message || String(error);
  if (/failed to fetch|networkerror|load failed/i.test(message)) {
    return new Error(`VideoDL is not running at ${origin}.`);
  }
  return error instanceof Error ? error : new Error(message);
}

export async function probeVideodlCookies(apiUrl) {
  const origin = assertLoopbackApiUrl(apiUrl);
  try {
    const response = await fetch(`${origin}/cookies/status`, {
      cache: "no-store",
    });
    if (!response.ok) {
      throw new Error(`VideoDL returned HTTP ${response.status}.`);
    }
    return response.json();
  } catch (error) {
    throw mapFetchError(error, origin);
  }
}

async function uploadNetscapeCookies(apiUrl, netscapeText) {
  const origin = assertLoopbackApiUrl(apiUrl);
  const form = new FormData();
  form.append(
    "file",
    new Blob([netscapeText], { type: "text/plain" }),
    "youtube.cookies.txt"
  );
  try {
    const response = await fetch(`${origin}/cookies/upload`, {
      method: "POST",
      body: form,
    });
    if (!response.ok) {
      let detail = `VideoDL returned HTTP ${response.status}.`;
      try {
        const payload = await response.json();
        if (typeof payload?.detail === "string" && payload.detail) {
          detail = payload.detail;
        }
      } catch {
        // Keep the status-only message.
      }
      throw new Error(detail);
    }
    return response.json();
  } catch (error) {
    throw mapFetchError(error, origin);
  }
}

export async function syncVideodlCookieAlarm() {
  const settings = await getVideodlCookieSettings();
  if (!settings.videodlCookieAutoSync) {
    await chrome.alarms.clear(ALARM_NAME);
    return { enabled: false };
  }
  await chrome.alarms.create(ALARM_NAME, {
    periodInMinutes: settings.videodlCookieIntervalMinutes,
  });
  return { enabled: true, periodInMinutes: settings.videodlCookieIntervalMinutes };
}

/**
 * Collect YouTube/Google cookies and POST a Netscape file to local VideoDL.
 * Never logs cookie names or values.
 */
export async function syncVideodlCookies({ requestPermission = false } = {}) {
  const settings = await getVideodlCookieSettings();
  assertLoopbackApiUrl(settings.videodlCookieApiUrl);

  try {
    if (requestPermission) {
      const granted = await requestCookiesPermission();
      if (!granted) {
        throw new Error("Cookie access was not granted.");
      }
    } else {
      const granted = await hasCookiesPermission();
      if (!granted) {
        throw new Error("Cookie access is not granted.");
      }
    }

    const cookies = await collectAllowedCookies();
    if (!cookies.length) {
      throw new Error(
        "No YouTube cookies found. Open youtube.com while signed in, then sync again."
      );
    }

    const signedIn = hasYoutubeLoginCookies(cookies);
    const uploaded = await uploadNetscapeCookies(
      settings.videodlCookieApiUrl,
      cookiesToNetscape(cookies)
    );
    const lastSyncedAt =
      typeof uploaded?.uploadedAt === "string" && uploaded.uploadedAt
        ? uploaded.uploadedAt
        : new Date().toISOString();

    const state = await saveVideodlCookieSyncState({
      lastSyncedAt,
      cookieCount: cookies.length,
      lastError: null,
      signedIn,
    });
    return state;
  } catch (error) {
    const lastError = error?.message || String(error);
    await saveVideodlCookieSyncState({ lastError });
    throw error instanceof Error ? error : new Error(lastError);
  }
}
